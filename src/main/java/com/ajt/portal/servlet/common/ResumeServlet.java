package com.ajt.portal.servlet.common;

import com.ajt.portal.model.Student;
import com.ajt.portal.model.User;
import com.ajt.portal.service.StudentService;
import jakarta.servlet.ServletException;
import jakarta.servlet.annotation.WebServlet;
import jakarta.servlet.http.HttpServlet;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import jakarta.servlet.http.HttpSession;

import java.io.File;
import java.io.FileInputStream;
import java.io.IOException;
import java.io.OutputStream;
import java.nio.file.Path;
import java.nio.file.Paths;

@WebServlet(name = "ResumeServlet", urlPatterns = {"/resume/download"})
public class ResumeServlet extends HttpServlet {

    private final StudentService studentService = new StudentService();
    private final com.ajt.portal.service.ApplicationService applicationService = new com.ajt.portal.service.ApplicationService();

    @Override
    protected void doGet(HttpServletRequest request, HttpServletResponse response)
            throws ServletException, IOException {
        HttpSession session = request.getSession(false);
        User currentUser = (session != null) ? (User) session.getAttribute("currentUser") : null;

        if (currentUser == null) {
            response.sendError(HttpServletResponse.SC_UNAUTHORIZED, "Please sign in to access resumes.");
            return;
        }

        String studentIdStr = request.getParameter("studentId");
        int studentId = 0;
        try {
            studentId = Integer.parseInt(studentIdStr);
        } catch (NumberFormatException ignored) {
        }

        Student student = null;
        if (studentId > 0) {
            student = studentService.getStudentById(studentId);
        } else if (currentUser.isStudent()) {
            student = studentService.getStudentByUserId(currentUser.getUserId());
        }

        if (student == null || student.getResumePath() == null) {
            response.sendError(HttpServletResponse.SC_NOT_FOUND, "Resume file not found.");
            return;
        }

        // Authorization check: Admins can view any resume; students can only view their own; HR can only view resumes of students who applied to their company
        if (currentUser.isStudent() && student.getUserId() != currentUser.getUserId()) {
            response.sendError(HttpServletResponse.SC_FORBIDDEN, "Access denied to this resume.");
            return;
        }

        if (currentUser.isCompanyHr()) {
            if (currentUser.getCompanyId() == null || !applicationService.hasStudentAppliedToCompany(student.getStudentId(), currentUser.getCompanyId())) {
                response.sendError(HttpServletResponse.SC_FORBIDDEN, "Access denied: Candidate has not applied to your company drives.");
                return;
            }
        }

        String appRealPath = getServletContext().getRealPath("/");
        Path resumeFullPath = Paths.get(appRealPath, student.getResumePath()).normalize();

        // Prevent path traversal
        if (!resumeFullPath.startsWith(Paths.get(appRealPath).normalize())) {
            response.sendError(HttpServletResponse.SC_FORBIDDEN, "Invalid path.");
            return;
        }

        File resumeFile = resumeFullPath.toFile();
        if (!resumeFile.exists() || !resumeFile.isFile()) {
            // If file does not exist on disk (e.g. demo data), return a generated text preview
            response.setContentType("text/plain");
            response.getWriter().println("Resume document for " + student.getFullName() + " (" + student.getEnrollmentNumber() + ")");
            response.getWriter().println("Branch: " + student.getBranch() + " | CGPA: " + student.getCgpa());
            response.getWriter().println("Demo document preview generated by Placement Portal.");
            return;
        }

        String fileName = resumeFile.getName();
        String mimeType = getServletContext().getMimeType(fileName);
        if (mimeType == null) {
            mimeType = "application/octet-stream";
        }

        response.setContentType(mimeType);
        response.setContentLengthLong(resumeFile.length());
        response.setHeader("Content-Disposition", "inline; filename=\"" + fileName + "\"");

        try (FileInputStream in = new FileInputStream(resumeFile);
             OutputStream out = response.getOutputStream()) {
            byte[] buffer = new byte[8192];
            int bytesRead;
            while ((bytesRead = in.read(buffer)) != -1) {
                out.write(buffer, 0, bytesRead);
            }
        }
    }
}

